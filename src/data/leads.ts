import type { Company } from "@/lib/lead-score";

type Seed = Omit<Company, "draftSubject" | "draftBody" | "filedLeadId" | "lastTouch" | "status" | "scoutBatch"> & {
  status?: Company["status"];
};

function card(row: Seed): Company {
  const company: Company = {
    ...row,
    status: row.status ?? "watch",
    filedLeadId: "",
    draftSubject: "",
    draftBody: "",
    lastTouch: "2026-09-17",
    scoutBatch: "seed-2026-09",
  };
  const draft = draftForCompany(company);
  return { ...company, draftSubject: draft.subject, draftBody: draft.body };
}

